/**
 * use-private-page-title.ts — عنوان تب برای صفحه‌های داخل حساب.
 * ─────────────────────────────────────────────────────────────────────────────
 * صفحه‌های عمومی (لندینگ، مستندات، آموزش‌ها) از `useSEO` استفاده می‌کردند،
 * ولی هیچ‌کدام از صفحه‌های داخل حساب هیچ عنوانی ست نمی‌کردند. نتیجه: بعد از
 * رفتن از صفحه‌ی اصلی به داشبورد، عنوان تبِ مرورگر روی عنوان پیش‌فرض سایت
 * می‌ماند — یعنی تاریخچه، بوکمارک و ده تبِ باز همگی یک اسم دارند.
 *
 * این هوک همان `useSEO` است با دو تفاوت که برای صفحه‌ی خصوصی معنی دارند:
 *
 *  - **`noindex` همیشه روشن.** `robots.txt` فقط جلوی *خزیدن* را می‌گیرد؛
 *    گوگل هنوز می‌تواند یک URL را که جایی لینک شده ایندکس کند. تنها تضمین
 *    واقعی، متاتگ `noindex` روی خود صفحه است — همان چیزی که docstring
 *    `use-seo.ts` هم می‌گوید.
 *  - **بدون `route`.** canonical و hreflang برای صفحه‌ای که نباید ایندکس
 *    شود بی‌معنا (و گمراه‌کننده) است.
 */
import { useSEO } from "@/hooks/use-seo";

export function usePrivatePageTitle(title: string) {
  useSEO({ title, noindex: true });
}
